const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const path=require('node:path');
const fs=require('node:fs');
const db=new URL(process.env.TEST_DATABASE_URL||'');
if(!['localhost','127.0.0.1'].includes(db.hostname)||!db.pathname.endsWith('_test'))throw Error('Només base local de proves');
const dist=path.resolve(process.env.TEST_UI_DIST||'');
if(!fs.existsSync(path.join(dist,'index.html')))throw Error('Cal TEST_UI_DIST amb la compilació VITE_API_URL=/api');
process.env.DATABASE_URL=db.toString();process.env.DIRECT_URL=db.toString();
process.env.JWT_SECRET=crypto.randomBytes(40).toString('hex');process.env.NODE_ENV='test';process.env.VAPID_PUBLIC_KEY='';process.env.VAPID_PRIVATE_KEY='';
const {chromium}=require('../../frontend/node_modules/playwright-core');
const bcrypt=require('bcrypt');
const {prisma}=require('../dist/prisma');
const app=require('../dist/index').default;
const express=require('express');
let server,browser;
(async()=>{
 const suffix=crypto.randomBytes(5).toString('hex');
 const association=await prisma.agrupacio.create({data:{nom:'AVPC fictícia navegador '+suffix}});
 const user=await prisma.usuari.create({data:{nom:'Administrador fictici',usuari:'browser-'+suffix,rol:'AGRUPACIO',agrupacioId:association.id,contrasenya:await bcrypt.hash('123456',12)}});
 app.use((req,res,next)=>{res.removeHeader('Content-Security-Policy');next();});
 app.use(express.static(dist));app.get('*',(_req,res)=>res.sendFile(path.join(dist,'index.html')));
 server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
 const base='http://127.0.0.1:'+server.address().port;
 browser=await chromium.launch({headless:true,channel:'msedge'});
 const context=await browser.newContext({viewport:{width:390,height:844}});
 await context.route('**/*',route=>{const u=new URL(route.request().url());return u.hostname==='127.0.0.1'?route.continue():route.abort();});
 const page=await context.newPage();page.setDefaultTimeout(60000);const violations=[];
 page.on('console',msg=>{if(/violates.*Content Security Policy|Refused to/i.test(msg.text()))violations.push(msg.text());});
 await page.goto(base+'/login',{waitUntil:'domcontentloaded',timeout:60000});
 await page.locator('#login-name').fill(user.usuari);await page.locator('#login-password').fill('123456');
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.locator('#confirm-password').waitFor();
 const password='Frase-ficticia-'+suffix+'!';
 await page.locator('#login-password').fill(password);await page.locator('#confirm-password').fill(password);
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.waitForFunction(()=>sessionStorage.getItem('token'));
 assert.equal(await page.locator('#mfa-secret, #mfa-code').count(),0);
 const token=await page.evaluate(()=>sessionStorage.getItem('token'));
 assert.equal(await page.evaluate(()=>localStorage.getItem('token')),null);
 await page.goto(base+'/gestio-avpc',{waitUntil:'domcontentloaded',timeout:60000});
 await page.getByRole('button',{name:/Voluntariat/}).click();
 await page.getByRole('button',{name:'+ Nou voluntari',exact:true}).click();
 const text=await page.locator('main').innerText();
 for(const forbidden of ['DNI','Codi postal','Data de naixement','Província','Altres emails'])assert.ok(!text.includes(forbidden),forbidden);
 await page.evaluate(()=>navigator.serviceWorker.ready);
 assert.ok(!(await page.evaluate(()=>caches.keys())).some(k=>k.startsWith('api-cache')));
 await context.setOffline(true);
 await page.getByText(/connexió|internet/i).first().waitFor();
 assert.equal(await page.getByRole('button',{name:'Crear voluntari',exact:true}).count(),0,'El formulari privat no es mostra sense connexió');
 await context.setOffline(false);await page.getByRole('button',{name:/Voluntariat/}).waitFor();
 await page.evaluate(async()=>{const c=await caches.open('api-cache-old-test');await c.put('/fake-private',new Response('fiction'));});
 await page.getByRole('button',{name:/Sortir/}).click();await page.locator('#login-name').waitFor();
 await page.waitForFunction(async()=>!(await caches.keys()).some(k=>k.startsWith('api-cache')));
 assert.equal((await fetch(base+'/api/auth/me',{headers:{Authorization:'Bearer '+token}})).status,401);
 assert.deepEqual(violations,[],'La CSP no ha de trencar el flux');
 assert.ok(await page.locator('meta[http-equiv="Content-Security-Policy"]').count());
 console.log('OK navegador mòbil: contrasenya pròpia sense segon factor, formulari mínim, bloqueig offline, purga de cache i sortida amb revocació.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();if(server)await new Promise(r=>server.close(r));await prisma.$disconnect();});
